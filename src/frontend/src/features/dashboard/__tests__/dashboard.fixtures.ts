/**
 * Polyfills window.matchMedia in jsdom for PrimeVue Select/Dialog listeners.
 */
export function ensureMatchMediaPolyfill(): void {
  if (typeof window === 'undefined') return;
  if (!window.matchMedia) {
    Object.defineProperty(window, 'matchMedia', {
      writable: true,
      value: vi.fn().mockImplementation((query: string) => ({
        matches: false,
        media: query,
        onchange: null,
        addListener: vi.fn(),
        removeListener: vi.fn(),
        addEventListener: vi.fn(),
        removeEventListener: vi.fn(),
        dispatchEvent: vi.fn(),
      })),
    });
  }
}

